// aggregateFunctionsCaseInsensitive holds the lower-cased names of the aggregate functions that ClickHouse matches case-insensitively, such as SUM and Count.
var aggregateFunctionsCaseInsensitive = func() map[string]bool {
	res := make(map[string]bool)
	for name, caseInsensitive := range aggregateFunctions {
		if caseInsensitive {
			res[strings.ToLower(name)] = true
		}
	}
	return res
}()

// isAggregateFunctionName reports whether name is a ClickHouse aggregate function as written, without combinator suffixes.
func isAggregateFunctionName(name string) bool {
	if _, ok := aggregateFunctions[name]; ok {
		return true
	}
	return aggregateFunctionsCaseInsensitive[strings.ToLower(name)]
}
