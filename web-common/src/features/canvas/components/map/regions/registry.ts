/**
 * Name of a built-in boundary set, as used in the `regions.boundaries` property.
 * `states` needs a country in `regions.country`;
 * `us_states` is the same as `states` with the country `US`.
 */
export type RegionBoundaries = "countries" | "states" | "us_states";

/** Feature property that dimension values can be matched against. */
export interface RegionKey {
  name: string;
  label: string;
}

export interface BoundarySet {
  label: string;
  /**
   * Keys that dimension values can match, in priority order for automatic matching.
   * The `name` key also matches the region's aliases.
   */
  keys: RegionKey[];
}

/** Matches the dimension values against every key of the boundary set. */
export const AUTO_REGION_KEY = "auto";

/** Country of the `states` boundary set when none is given, such as for `us_states`. */
export const DEFAULT_STATES_COUNTRY = "US";

const NAME_KEY: RegionKey = { name: "name", label: "Name" };

/*
 * Boundaries are generated by `web-common/scripts/generate-map-boundaries.ts` into `web-common/static`,
 * which both apps serve at `/map-boundaries`.
 * Every feature has a unique `id`, a display `name`, the codes listed in its set's `keys`,
 * and `aliases`, a "|" separated list of other names for the region.
 */
export const BOUNDARY_SETS: Record<RegionBoundaries, BoundarySet> = {
  countries: {
    label: "Countries",
    keys: [
      { name: "iso_a2", label: "ISO 3166-1 alpha-2 (US)" },
      { name: "iso_a3", label: "ISO 3166-1 alpha-3 (USA)" },
      { name: "iso_n3", label: "ISO 3166-1 numeric (840)" },
      NAME_KEY,
    ],
  },
  states: {
    label: "States and provinces",
    keys: [
      { name: "code", label: "Code (CA)" },
      { name: "iso_3166_2", label: "ISO 3166-2 (US-CA)" },
      { name: "fips", label: "FIPS code, US only (06)" },
      NAME_KEY,
    ],
  },
  us_states: {
    label: "US states",
    keys: [
      { name: "postal", label: "Postal code (CA)" },
      { name: "iso_3166_2", label: "ISO 3166-2 (US-CA)" },
      { name: "fips", label: "FIPS code (06)" },
      NAME_KEY,
    ],
  },
};

export function isRegionBoundaries(value: unknown): value is RegionBoundaries {
  return typeof value === "string" && value in BOUNDARY_SETS;
}

/**
 * Name of the built-in boundary file in the manifest, such as `countries` or `states/DE`.
 * Returns undefined for `states` without a valid country.
 */
export function boundaryFileName(
  boundaries: RegionBoundaries,
  country: string | undefined,
): string | undefined {
  switch (boundaries) {
    case "countries":
      return "countries";
    case "states":
      return country && /^[A-Z]{2}$/.test(country)
        ? `states/${country}`
        : undefined;
    case "us_states":
      return `states/${DEFAULT_STATES_COUNTRY}`;
  }
}

/** Guesses the boundary set from a dimension name such as `country` or `billing_state`. */
export function guessRegionBoundaries(
  dimension: string,
): { boundaries: RegionBoundaries; country?: string } | undefined {
  const name = dimension.toLowerCase();
  if (name.includes("country")) return { boundaries: "countries" };
  if (name.includes("state") || name.includes("province")) {
    return { boundaries: "states", country: DEFAULT_STATES_COUNTRY };
  }
  return undefined;
}
