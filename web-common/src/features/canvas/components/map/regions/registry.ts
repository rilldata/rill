import type * as GeoJSON from "geojson";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

/** Name of a built-in boundary set, as used in the `regions.boundaries` property. */
export type RegionBoundaries = "countries" | "us_states";

/** Feature property that dimension values can be matched against. */
export interface RegionKey {
  name: string;
  label: string;
}

export interface BoundarySet {
  label: string;
  /**
   * Keys that dimension values can match, in priority order for automatic matching.
   * The `name` key also matches the region's aliases.
   */
  keys: RegionKey[];
  load: () => Promise<GeoJSON.FeatureCollection>;
}

/** Matches the dimension values against every key of the boundary set. */
export const AUTO_REGION_KEY = "auto";

const NAME_KEY: RegionKey = { name: "name", label: "Name" };

/*
 * Boundaries are generated by `web-common/scripts/generate-map-boundaries.ts`.
 * Every feature has a unique `id`, a display `name`, the codes listed in its set's `keys`,
 * and `aliases`, a "|" separated list of other names for the region.
 *
 * TODO: Load the boundary sets from the CDN instead of bundling them into web-common.
 * Bundling is fine for the small sets below,
 * but does not scale to larger ones such as admin-1 regions for every country.
 */
export const BOUNDARY_SETS: Record<RegionBoundaries, BoundarySet> = {
  countries: {
    label: "Countries",
    keys: [
      { name: "iso_a2", label: "ISO 3166-1 alpha-2 (US)" },
      { name: "iso_a3", label: "ISO 3166-1 alpha-3 (USA)" },
      { name: "iso_n3", label: "ISO 3166-1 numeric (840)" },
      NAME_KEY,
    ],
    load: () =>
      loadBoundarySet("countries", () => import("./data/countries.topo.json")),
  },
  us_states: {
    label: "US states",
    keys: [
      { name: "postal", label: "Postal code (CA)" },
      { name: "iso_3166_2", label: "ISO 3166-2 (US-CA)" },
      { name: "fips", label: "FIPS code (06)" },
      NAME_KEY,
    ],
    load: () =>
      loadBoundarySet("us_states", () => import("./data/us_states.topo.json")),
  },
};

export function isRegionBoundaries(value: unknown): value is RegionBoundaries {
  return typeof value === "string" && value in BOUNDARY_SETS;
}

/** Guesses the boundary set from a dimension name such as `country` or `billing_state`. */
export function guessRegionBoundaries(
  dimension: string,
): RegionBoundaries | undefined {
  const name = dimension.toLowerCase();
  if (name.includes("country")) return "countries";
  if (name.includes("state")) return "us_states";
  return undefined;
}

const loaded = new Map<string, Promise<GeoJSON.FeatureCollection>>();

function loadBoundarySet(
  name: RegionBoundaries,
  importer: () => Promise<{ default: unknown }>,
): Promise<GeoJSON.FeatureCollection> {
  let promise = loaded.get(name);
  if (!promise) {
    promise = importer().then((mod) => {
      const topology = mod.default as Topology<
        Record<string, GeometryCollection>
      >;
      return feature(topology, topology.objects[name]);
    });
    // Drop failed loads so a later render can retry.
    promise.catch(() => loaded.delete(name));
    loaded.set(name, promise);
  }
  return promise;
}
